"""Write assets/header-light.svg and assets/header-dark.svg.

Static files on master, regenerated by hand when the wording changes:
    python scripts/header.py
The name fades in, the tagline types out, and the contribution squares pulse. Viewers who
prefer reduced motion see the finished banner.
"""

from __future__ import annotations

from pathlib import Path

TAGLINE = "DevOps · Cloud · Linux sysadmin · Cybersecurity"
DETAIL = "Auckland, New Zealand · GitHub since 2021 · 270+ source repositories"
THEMES = {
    "light": {
        "bg": "#ffffff",
        "border": "#d1d9e0",
        "fg": "#1f2328",
        "muted": "#59636e",
        "accent": "#0969da",
    },
    "dark": {
        "bg": "#0d1117",
        "border": "#3d444d",
        "fg": "#f0f6fc",
        "muted": "#9198a1",
        "accent": "#4493f8",
    },
}
FONT = "-apple-system, BlinkMacSystemFont, 'Segoe UI', 'Noto Sans', Helvetica, Arial, sans-serif"
# Opacity pattern for the 5 x 4 contribution grid on the right.
GRID = [
    [0.25, 0.45, 0.7, 1.0, 0.45],
    [0.45, 1.0, 0.25, 0.7, 0.25],
    [0.7, 0.25, 1.0, 0.45, 1.0],
    [1.0, 0.7, 0.45, 0.25, 0.7],
]


def render(c: dict[str, str]) -> str:
    steps = len(TAGLINE)
    squares = []
    for r, line in enumerate(GRID):
        for col, opacity in enumerate(line):
            delay = (r * 5 + col) * 0.11
            squares.append(
                f'<rect class="sq" style="animation-delay:{delay:.2f}s" x="{840 + col * 18}" y="{52 + r * 18}" '
                f'width="14" height="14" rx="3" fill="{c["accent"]}" fill-opacity="{opacity}"/>'
            )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="1012" height="200" viewBox="0 0 1012 200" role="img" aria-label="M Amirul. {TAGLINE} {DETAIL}">
  <title>M Amirul</title>
  <style>
    .name{{opacity:0;animation:rise .7s ease-out .1s forwards}}
    .detail{{opacity:0;animation:rise .6s ease-out 2.9s forwards}}
    .cover{{animation:type 2.2s steps({steps}) .7s forwards}}
    .caret{{animation:caret 2.2s steps({steps}) .7s forwards,blink 1s step-end 2.9s 4}}
    .sq{{transform-box:fill-box;transform-origin:center;animation:pulse 2.8s ease-in-out infinite}}
    @keyframes rise{{from{{opacity:0;transform:translateY(6px)}}to{{opacity:1;transform:none}}}}
    @keyframes type{{from{{transform:translateX(0)}}to{{transform:translateX(600px)}}}}
    @keyframes caret{{from{{transform:translateX(0)}}to{{transform:translateX(600px)}}}}
    @keyframes blink{{50%{{opacity:0}}}}
    @keyframes pulse{{0%,100%{{transform:scale(1)}}50%{{transform:scale(.82)}}}}
    @media (prefers-reduced-motion:reduce){{.name,.detail{{animation:none;opacity:1}}.cover,.caret{{display:none}}.sq{{animation:none}}}}
  </style>
  <rect x="0.5" y="0.5" width="1011" height="199" rx="6" fill="{c["bg"]}" stroke="{c["border"]}"/>
  <g font-family="{FONT}">
    <text class="name" x="40" y="84" font-size="40" font-weight="600" fill="{c["fg"]}">M Amirul</text>
    <text x="40" y="120" font-size="18" fill="{c["muted"]}">{TAGLINE}</text>
    <rect class="cover" x="38" y="100" width="610" height="28" fill="{c["bg"]}"/>
    <rect class="caret" x="40" y="104" width="2" height="20" fill="{c["accent"]}"/>
    <text class="detail" x="40" y="160" font-size="14" fill="{c["muted"]}">{DETAIL}</text>
  </g>
  {"".join(squares)}
</svg>
"""


def main() -> None:
    out = Path(__file__).resolve().parent.parent / "assets"
    out.mkdir(exist_ok=True)
    for name, colours in THEMES.items():
        path = out / f"header-{name}.svg"
        path.write_text(render(colours), encoding="utf-8", newline="\n")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
